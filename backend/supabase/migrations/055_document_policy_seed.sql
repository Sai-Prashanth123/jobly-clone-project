-- 055_document_policy_seed.sql
--
-- Which documents each work status needs, as data rather than as code.
--
-- Tables and seed ONLY. Nothing reads these yet, so applying this migration
-- changes no behaviour whatsoever — the same shape as 052 for permissions.
--
-- THE SEED IS GENERATED FROM THE RUNNING CODE
-- (npx tsx scripts/generateDocumentPolicy.ts --sql), never typed by hand. It
-- collapses six overlapping sources into one answer per cell:
--
--   ROW_VISA_EXCLUDE          deny-list, beats everything
--   ROW_VISA_GATE             allow-list, absent key = everyone
--   inline wizard rules       NewEmployee.tsx — in no table at all
--   getRequiredIdentityTypes  the required union
--   EMPLOYER_ROW_VISA_GATE    employer rows, absent key = nobody
--   EMPLOYER_DOC_ROWS         which documents the employer issues
--
-- Those can contradict each other today and have: the Green Card fix took
-- three passes because i140 was gated one way while i140_questionnaire was
-- excluded another. One cell holding one value cannot.
--
-- src/lib/documentPolicy.ts carries the same policy compiled in as a fallback,
-- so an empty or unreachable table behaves exactly like today rather than
-- blocking onboarding or demanding nothing.

CREATE TABLE IF NOT EXISTS public.document_types (
  key         text PRIMARY KEY,
  label       text NOT NULL,
  -- 'employee' or 'employer'. An employer-issued document is never REQUIRED of
  -- an employee: they cannot produce an LCA, and demanding one would make
  -- onboarding impossible to finish.
  issued_by   text NOT NULL DEFAULT 'employee',
  has_expiry  boolean NOT NULL DEFAULT false,
  -- Other names the same document has been filed under. documents.type is free
  -- text, so one document collects spellings; a spelling missing here is
  -- invisible to the onboarding check and the employee is asked for something
  -- they have already uploaded.
  aliases     text[] NOT NULL DEFAULT '{}',
  sort_order  integer NOT NULL DEFAULT 0,
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.document_requirements (
  document_key text NOT NULL REFERENCES public.document_types(key) ON DELETE CASCADE,
  visa_type    text NOT NULL,
  -- 'required' | 'optional' | 'hidden'
  state        text NOT NULL DEFAULT 'optional',
  updated_at   timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (document_key, visa_type)
);

CREATE INDEX IF NOT EXISTS document_requirements_visa_idx
  ON public.document_requirements (visa_type);

