-- 052_role_permissions.sql
--
-- Admin-editable role permissions. Tables and seed ONLY: nothing reads these
-- yet, so applying this migration changes no behaviour whatsoever.
--
-- THE SEED IS GENERATED FROM THE RUNNING CODE, not from the permissions table
-- that Admin Settings displays today. That table and the code disagree - it
-- shows Activity Logs as admin-only while requireRole admits HR, and it omits
-- HR from reports where the routes allow it. Seeding from the screen would
-- have moved 113 of 256 routes on day one and taken 30 away from HR, which is
-- the same shape as the document regression HR reported in October. Seeded
-- from the code, day one behaves exactly as today and every later change is
-- somebody's deliberate decision.
--
-- A key's grant is the INTERSECTION of the role sets of the routes behind it:
-- a role that cannot reach every route under a key is not ticked for it, so
-- the fold can never widen access.

CREATE TABLE IF NOT EXISTS public.roles (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  key         text UNIQUE NOT NULL,
  label       text NOT NULL,
  is_builtin  boolean NOT NULL DEFAULT false,
  created_at  timestamptz NOT NULL DEFAULT now()
);

-- The six built-ins mirror the user_role enum. The enum stays authoritative
-- for portal_users.role: a Postgres enum value can never be removed, so custom
-- roles live here instead of being added to it.
INSERT INTO public.roles (key, label, is_builtin) VALUES
  ('admin', 'Admin', true),
  ('hr', 'HR', true),
  ('operations', 'Project Manager', true),
  ('finance', 'Finance', true),
  ('legal', 'Legal', true),
  ('employee', 'Employee', true)
ON CONFLICT (key) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.permissions (
  key         text PRIMARY KEY,
  label       text NOT NULL,
  group_name  text NOT NULL,
  -- A custom permission is inert until a developer references its key. The
  -- create form says so, so nobody believes a new row has locked anything.
  is_custom   boolean NOT NULL DEFAULT false,
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.role_permissions (
  role_key        text NOT NULL REFERENCES public.roles(key) ON DELETE CASCADE,
  permission_key  text NOT NULL REFERENCES public.permissions(key) ON DELETE CASCADE,
  granted         boolean NOT NULL DEFAULT true,
  updated_at      timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (role_key, permission_key)
);

CREATE INDEX IF NOT EXISTS role_permissions_role_idx ON public.role_permissions (role_key);

