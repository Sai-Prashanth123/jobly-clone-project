-- 059_paf_document.sql
--
-- Add the Public Access File (PAF) to the document catalogue.
--
-- HR: *"Could you please add PAF / Public access files."*
--
-- The PAF is the LCA public-disclosure file an employer must keep for each
-- certified LCA. It is employer-maintained by law, so it is issued_by
-- 'employer': tracked, visible to admin and HR, never shown to the employee
-- and never part of their required set. An employee cannot produce one, and
-- demanding it would stop them ever reaching 100%.
--
-- It is surfaced instead through the "employer paperwork missing" notice
-- alongside Copy of LCA and the E-Verify Letter, which is where the rest of
-- what the company owes for an H-1B already appears.
--
-- Visible for h1b only, hidden for the other nine work statuses — the same
-- shape as i129 and lca_copy. Values generated by
--   npx tsx scripts/generateDocumentPolicy.ts --sql
-- and transcribed for this single document rather than reseeding all 40.

INSERT INTO public.document_types (key, label, issued_by, has_expiry, category)
VALUES ('paf', 'Public Access File (PAF)', 'employer', false, 'employer')
ON CONFLICT (key) DO UPDATE
  SET label = EXCLUDED.label,
      issued_by = EXCLUDED.issued_by,
      category = EXCLUDED.category;

-- 'optional' for an employer document means "tracked"; the Document Policy
-- page offers only Tracked / Not applicable for these, because Required is
-- not a coherent answer for paperwork the employee cannot supply.
INSERT INTO public.document_requirements (document_key, visa_type, state) VALUES
  ('paf', 'h1b', 'optional'),
  ('paf', 'l1', 'hidden'),
  ('paf', 'l2', 'hidden'),
  ('paf', 'opt', 'hidden'),
  ('paf', 'stem_opt', 'hidden'),
  ('paf', 'gc', 'hidden'),
  ('paf', 'citizen', 'hidden'),
  ('paf', 'tn', 'hidden'),
  ('paf', 'h4_ead', 'hidden'),
  ('paf', 'other', 'hidden')
ON CONFLICT (document_key, visa_type) DO NOTHING;
