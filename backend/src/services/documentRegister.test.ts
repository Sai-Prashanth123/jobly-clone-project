import { describe, it, expect, vi, beforeEach } from 'vitest';

/**
 * Registering a file the browser put straight into storage.
 *
 * This is the step that replaces multer's implicit guarantees. When the bytes
 * travelled through this server, it knew what had arrived and how big it was.
 * Now the client PUTs to S3 and then says "there's a file at this path" — so
 * every one of those claims has to be checked here, and each test below is one
 * way of lying.
 */

const stat = vi.fn();
const remove = vi.fn();
const signedUploadUrl = vi.fn();
const insert = vi.fn();
const maybeSingle = vi.fn();

// Minimal supabase double: `.from('documents')` is used for the duplicate
// lookup and for the insert, so the chain has to serve both.
const from = vi.fn(() => ({
  select: () => ({ eq: () => ({ maybeSingle }) }),
  insert: (row: unknown) => {
    insert(row);
    return { select: () => ({ single: async () => ({ data: { id: 'doc-1', ...(row as object) }, error: null }) }) };
  },
}));

vi.mock('../config/supabase', () => ({ supabaseAdmin: { from: (...a: unknown[]) => from(...(a as [])) } }));
vi.mock('../lib/storage', () => ({
  storageProvider: {
    stat: (...a: unknown[]) => stat(...(a as [])),
    remove: (...a: unknown[]) => remove(...(a as [])),
    signedUploadUrl: (...a: unknown[]) => signedUploadUrl(...(a as [])),
  },
}));
vi.mock('mammoth', () => ({ default: {} }));
vi.mock('word-extractor', () => ({ default: class {} }));
vi.mock('xlsx', () => ({}));

import { registerUploadedDocument, createDocumentUploadTarget } from './storage.service';
import { uniqueObjectPath } from '../lib/storage/objectPath';
import { MAX_UPLOAD_BYTES } from '../lib/storage/uploadLimits';

const EMP = '3b79bdb6-d432-4910-8bf5-1a5f0836159f';
const OTHER = 'ae9f62ab-0beb-41d1-8af1-8f4715b5df62';

const register = (over: Record<string, unknown> = {}) => registerUploadedDocument({
  entityType: 'employee', entityId: EMP,
  storagePath: uniqueObjectPath(EMP, 'passport.pdf'),
  uploadedBy: 'user-1', fileName: 'passport.pdf',
  ...over,
} as Parameters<typeof registerUploadedDocument>[0]);

beforeEach(() => {
  vi.clearAllMocks();
  maybeSingle.mockResolvedValue({ data: null, error: null });
  stat.mockResolvedValue({ size: 1024, contentType: 'application/pdf' });
  remove.mockResolvedValue(undefined);
});

describe('claiming an upload that is not yours', () => {
  it('refuses a path under another record', async () => {
    await expect(register({ storagePath: uniqueObjectPath(OTHER, 'passport.pdf') }))
      .rejects.toThrow(/does not belong/i);
    expect(insert).not.toHaveBeenCalled();
  });

  it('refuses a traversal out of the prefix', async () => {
    await expect(register({ storagePath: `${EMP}/../${OTHER}/1700000000-abcdef12-x.pdf` }))
      .rejects.toThrow(/does not belong/i);
    expect(insert).not.toHaveBeenCalled();
  });

  // A path nobody issued — not generated by uniqueObjectPath.
  it('refuses an invented path', async () => {
    await expect(register({ storagePath: `${EMP}/passport.pdf` }))
      .rejects.toThrow(/does not belong/i);
    expect(insert).not.toHaveBeenCalled();
  });
});

describe('claiming an upload that did not happen', () => {
  it('refuses when nothing is at that path', async () => {
    stat.mockResolvedValue(null);
    await expect(register()).rejects.toThrow(/did not finish/i);
    expect(insert).not.toHaveBeenCalled();
  });

  it('rejects and removes a zero-byte file', async () => {
    stat.mockResolvedValue({ size: 0 });
    await expect(register()).rejects.toThrow(/empty/i);
    expect(remove).toHaveBeenCalledTimes(1);
    expect(insert).not.toHaveBeenCalled();
  });
});

describe('the size limit is enforced against storage, not the request', () => {
  it('rejects an oversize file AND deletes it', async () => {
    stat.mockResolvedValue({ size: MAX_UPLOAD_BYTES + 1 });
    await expect(register()).rejects.toThrow(/larger than 100 MB/i);

    // Deleting matters: without it the limit is advisory and the bucket fills
    // with files no row points at.
    expect(remove).toHaveBeenCalledTimes(1);
    const [, paths] = remove.mock.calls[0];
    expect(paths).toHaveLength(1);
    expect(insert).not.toHaveBeenCalled();
  });

  it('accepts a file exactly at the limit', async () => {
    stat.mockResolvedValue({ size: MAX_UPLOAD_BYTES });
    await expect(register()).resolves.toBeTruthy();
    expect(remove).not.toHaveBeenCalled();
  });
});

describe('registering the same object twice', () => {
  it('is refused, and does NOT delete the object', async () => {
    maybeSingle.mockResolvedValue({ data: { id: 'existing' }, error: null });
    await expect(register()).rejects.toThrow(/already been saved/i);

    // The object belongs to the row that got there first — removing it here
    // would destroy a file that document still points at.
    expect(remove).not.toHaveBeenCalled();
    expect(insert).not.toHaveBeenCalled();
  });
});

describe('a legitimate registration', () => {
  it('stores the row with a server-derived type', async () => {
    await register({ fileName: 'payload.html' });
    const row = insert.mock.calls[0][0] as Record<string, string>;
    // Never text/html, whatever the client called it.
    expect(row.type).toBe('application/octet-stream');
    expect(row.entity_id).toBe(EMP);
    expect(row.storage_url).toBeNull();
  });

  it('honours an explicit name and document type', async () => {
    await register({ nameOverride: 'Passport', docTypeOverride: 'Passport' });
    const row = insert.mock.calls[0][0] as Record<string, string>;
    expect(row.name).toBe('Passport');
    expect(row.type).toBe('Passport');
  });
});

describe('issuing an upload target', () => {
  it('signs a server-generated key, never one the client chose', async () => {
    signedUploadUrl.mockResolvedValue('https://s3.example/put');
    const out = await createDocumentUploadTarget('employee', EMP, 'my scan (1).pdf');

    expect(out.storagePath.startsWith(`${EMP}/`)).toBe(true);
    expect(out.storagePath).not.toContain(' ');
    expect(out.contentType).toBe('application/pdf');
    expect(out.maxBytes).toBe(MAX_UPLOAD_BYTES);
  });

  it('signs a dangerous file as a plain download', async () => {
    signedUploadUrl.mockResolvedValue('https://s3.example/put');
    const out = await createDocumentUploadTarget('employee', EMP, 'page.html');
    expect(out.contentType).toBe('application/octet-stream');
    // The type is part of the signature, so the browser cannot substitute one.
    const [, , , opts] = signedUploadUrl.mock.calls[0] as [string, string, number, { contentType: string }];
    expect(opts.contentType).toBe('application/octet-stream');
  });
});
